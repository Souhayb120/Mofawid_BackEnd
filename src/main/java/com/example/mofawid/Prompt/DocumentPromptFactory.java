    private String safe(String value) {

        if (value == null || value.isBlank()) {
            return "[المعلومة غير متوفرة]";
        }

        return value;
    }
    private String formatMissions(List<Mission> missions) {

        if (missions == null || missions.isEmpty()) {
            return "[لا توجد مهام]";
        }

        StringBuilder builder = new StringBuilder();

        for (Mission mission : missions) {

            builder.append("- المهمة: ")
                    .append(safe(mission.getTitle()))
                    .append("\n");

            builder.append("  الوصف: ")
                    .append(safe(mission.getDescription()))
                    .append("\n\n");
        }

        return builder.toString();
    }
    private String formatObservations(List<Observation> observations) {

        if (observations == null || observations.isEmpty()) {
            return "[لا توجد ملاحظات]";
        }

        StringBuilder builder = new StringBuilder();

        for (Observation observation : observations) {

            builder.append("- نوع الملاحظة: ")
                    .append(observation.getKind())
                    .append("\n");

            builder.append("  الوصف: ")
                    .append(safe(observation.getDescription()))
                    .append("\n");

            if (observation.getObservedAt() != null) {
                builder.append("  تاريخ المعاينة: ")
                        .append(observation.getObservedAt())
                        .append("\n");
            }

            builder.append("\n");
        }

        return builder.toString();
    }


